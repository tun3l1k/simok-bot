const MEAN_MULT = 1.2468; // средний множитель региона, на нём отстроены ставки

// rows: [код, макрорегион, вес кода]. Код привязан к макрорегиону, город выбирается внутри него.
// Средний множитель выравнивается весом московских кодов, чтобы ни у одного оператора не было бонуса.
function regions(rows) {
  const make = (t) => rows.flatMap(([code, d, w]) => {
    const cs = DISTRICTS[d];
    const tw = cs.reduce((a, c) => a + c[2], 0);
    return cs.map(([city, mult, cw]) => ({ code, city, mult, w: (d === 'msk' ? w * t : w) * (cw / tw) }));
  });
  const mean = (list) => list.reduce((a, c) => a + c.w * c.mult, 0) / list.reduce((a, c) => a + c.w, 0);
  let lo = 0.05, hi = 20;
  for (let i = 0; i < 40; i++) { const mid = (lo + hi) / 2; if (mean(make(mid)) < MEAN_MULT) lo = mid; else hi = mid; }
  return make((lo + hi) / 2).map((c) => ({ ...c, w: Math.round(c.w * 1000) / 1000 }));
}

