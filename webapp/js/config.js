const MEAN_MULT = 1.2468; // средний множитель региона, на нём отстроены ставки

// Реестр → список {code, city, mult, w} для оператора. Вес = число блоков номеров этого региона у оператора, поделённое
// между кодами набора. Средний множитель выравнивается весом Москвы, чтобы ни у одного оператора не было бонуса.
function regions(opId) {
  const make = (t) => {
    const acc = new Map();
    for (const [r, g, n] of REGISTRY.ops[opId]) {
      const name = REGISTRY.regions[r];
      const info = CITY[name];
      if (!info) continue;
      const codes = REGISTRY.groups[g].split(' ');
      for (const code of codes) {
        const k = `${code}|${info[0]}`;
        const w = (n / codes.length) * (name === 'Город Москва' ? t : 1);
        acc.set(k, { code, city: info[0], mult: info[1], w: (acc.get(k)?.w ?? 0) + w });
      }
    }
    return [...acc.values()];
  };
  const mean = (list) => list.reduce((a, c) => a + c.w * c.mult, 0) / list.reduce((a, c) => a + c.w, 0);
  let lo = 0.05, hi = 40;
  for (let i = 0; i < 40; i++) { const mid = (lo + hi) / 2; if (mean(make(mid)) < MEAN_MULT) lo = mid; else hi = mid; }
  return make((lo + hi) / 2).map((c) => ({ ...c, w: Math.round(c.w * 1000) / 1000 }));
}

